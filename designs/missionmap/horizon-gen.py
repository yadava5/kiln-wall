"""horizon-gen.py: the real southern skyline from Miami University, for the weather window.

    python3 horizon-gen.py          # writes horizon.js beside this file

Same 3DEP Terrarium z14 tiles as ground-gen.py (the kitty wallpaper's cache). From the
campus point at eye height 2 m, one ray per azimuth from due east (90) through south to due
west (270), stepped one sample (~7.4 m) at a time to the edge of the tiles; the horizon's
elevation angle on that bearing is the largest angle any sample subtends. The window draws
it as the land's silhouette, looking south, so east is on the left.
OUTPUT horizon.js: window.MM_HORIZON = {az0, az1, deg[N]}  (degrees above the eye's level)
"""
import json, math, os
import numpy as np
from PIL import Image

S = os.path.dirname(os.path.abspath(__file__))
LAT = 39.5070
UNI_LAT, UNI_LON = 39.5089, -84.7340
ZOOM, TW, TH = 14, 8, 5
X0, Y0 = 4331, 6229
CACHE = os.path.expanduser("~/.config/kitty/backgrounds/tiles/14")
N_AZ, EYE = 262, 2.0
n = 2 ** ZOOM
mpp = 156543.03 * math.cos(math.radians(LAT)) / n
el = np.zeros((TH * 256, TW * 256))
for ty in range(TH):
    for tx in range(TW):
        px = np.asarray(Image.open(f"{CACHE}/{X0 + tx}_{Y0 + ty}.png").convert("RGB"), dtype=np.float64)
        el[ty * 256:(ty + 1) * 256, tx * 256:(tx + 1) * 256] = px[..., 0] * 256 + px[..., 1] + px[..., 2] / 256 - 32768
ux = (UNI_LON + 180.0) / 360.0 * n * 256 / 256 * 256 / 256
cx = (UNI_LON + 180.0) / 360.0 * n * 256 - X0 * 256
cy = (1.0 - math.asinh(math.tan(math.radians(UNI_LAT))) / math.pi) / 2.0 * n * 256 - Y0 * 256
z0 = el[int(round(cy)), int(round(cx))] + EYE
deg = []
for k in range(N_AZ):
    az = math.radians(90 + 180 * k / (N_AZ - 1))           # compass, clockwise from north
    dx, dy = math.sin(az), -math.cos(az)                     # y runs south in the grid
    best, s = -90.0, 4.0
    while True:
        x, y = cx + dx * s, cy + dy * s
        if not (0 <= x < el.shape[1] - 1 and 0 <= y < el.shape[0] - 1): break
        a = math.degrees(math.atan2(el[int(y), int(x)] - z0, s * mpp))
        if a > best: best = a
        s += 1.0
    deg.append(round(best, 3))
print(f"campus at grid ({cx:.0f},{cy:.0f}), {z0:.0f} m; horizon {min(deg):.2f}..{max(deg):.2f} deg")
with open(os.path.join(S, "horizon.js"), "w") as fh:
    fh.write("// Generated by horizon-gen.py from 3DEP elevation (Terrarium z14 tiles): do not edit.\n")
    fh.write("window.MM_HORIZON=" + json.dumps({"az0": 90, "az1": 270, "deg": deg}, separators=(",", ":")) + ";\n")
